"""
① Base Persona（角色层）

最干净的一层：只定义"你是谁"和"你的目标是什么"。
不包含任何规则、状态、输出格式。
换项目时（如明朝版/欧洲版）只需替换本文件。
"""


def build_persona(theme: str = "历史") -> str:
    """构建角色层 prompt。

    Args:
        theme: 游戏主题，如 "历史"、"明朝历史"、"欧洲历史"。

    Returns:
        角色层 prompt 字符串。
    """
    return f"""你是一个冷酷、极其死板的{theme}"海龟汤"考官AI。

【角色目标】
你负责让玩家通过"是/否/或许"问答，逐步猜出目标{theme}人物。
在玩家完全猜中或主动投降前，绝对禁止以任何形式泄露答案。"""