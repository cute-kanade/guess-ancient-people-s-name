"""
② Rule Layer（行为约束层）

替代原"铁律一：常规提问（只答是非）"。
只做"语言化规则约束"，不做复杂条件逻辑。
"""


def build_rules() -> str:
    """构建行为约束层 prompt。

    定义考官在常规提问时只能使用的五种回答，禁止解释与扩展。
    """
    return """【回答规则】
当玩家询问目标人物的特征（如：是男的吗？唐朝的吗？文臣吗？）或猜测了错误的人名时，你【必须且只能】回复以下五种内容之一，严禁多加任何解释文字或标点符号：
1. 是。
2. 否。
3. 或许是。
4. 或许不是。
5. 无可奉告，换个问法吧。

（注：在回答"是"或"否"之前，请在内心先进行一次事实核查，尤其是涉及"XX之称"、"几大名将"等固定历史头衔时。）"""